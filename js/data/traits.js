const TRAIT_DATA = (function () {
  const list = [];
  const types = ['노말', '불꽃', '물', '풀', '전기', '얼음', '격투', '독', '땅', '비행', '에스퍼', '벌레', '바위', '고스트', '드래곤', '악', '강철', '페어리'];
  for (const id of types) list.push(Object.assign({ id, mode: 'count' }, TRAIT_DEFS[id], { breakpoints: TRAIT_DEFS[id].tiers }));
  for (const id in TRAIT_DEFS) {
    if (TRAIT_DEFS[id].kind === 'class') list.push(Object.assign({ id, mode: 'count' }, TRAIT_DEFS[id], { breakpoints: TRAIT_DEFS[id].tiers }));
  }
  for (const id in UNIQUE_DESC) list.push({ id, kind: 'unique', mode: 'count', tiers: [1], breakpoints: [1], desc: UNIQUE_DESC[id], steps: ['고유 시너지가 켜집니다.'], vals: {} });
  const map = {};
  for (const t of list) map[t.id] = t;
  return { list, map };
})();

function traitVal(id, key, tier) {
  const t = TRAIT_DATA.map[id];
  if (!t || !tier || !t.vals[key]) return 0;
  const arr = t.vals[key];
  return arr[Math.min(tier, arr.length) - 1];
}
